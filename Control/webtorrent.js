const APPROVED_DOMAINS = [
    ".edu",
    "arxiv.org",
    "jstor.org",
    "gutenberg.org",
    "archive.org",
    "doaj.org",
    "plato.stanford.edu",
    "zenodo.org",
    "osf.io",
    "localhost",
    "buddhanet.net"
];

const WebTorrentControl = {
    isWhitelisted(urlStr) {
        try {
            const parsed = new URL(urlStr);
            const hostname = parsed.hostname.toLowerCase();
            
            return APPROVED_DOMAINS.some(domain => {
                if (domain.startsWith('.')) {
                    return hostname.endsWith(domain);
                }
                return hostname === domain || hostname.endsWith('.' + domain);
            });
        } catch (err) {
            console.warn("[SECURITY] Malformed webseed URL rejected:", urlStr);
            return false;
        }
    },

    seed(fileOrSource, RayPayLoad, seedOptions, cb) {        
        if (!seedOptions || !seedOptions.urlList || seedOptions.urlList.length === 0) {
            console.info("[MVC.Control.webtorrent] Torrent creation canceled: empty urlList.");
            return;
        }

        const that = this;

        seedOptions.urlList.forEach(function(URL){
            if(!that.isWhitelisted(URL)){
                console.error(`[SECURITY REJECTED] Domain not allowed by whitelist policy: ${URL}`);
                alert(`[REJECTED] Webseed domain is not whitelisted: ${URL}`);
                return;
            }
        });

        const client = window.client || window.webtorrentClient;
        if (!client) {
            console.error("[MVC.Control.webtorrent] window.client WebTorrent instance not found.");
            return;
        }

        client.seed(fileOrSource, seedOptions, async (torrent) => {
            console.info(`[MVC.Control.webtorrent] Torrent active. InfoHash: ${torrent.infoHash}`);

            if (window.MVC?.Hook?.Hero && typeof window.MVC.Hook.Hero.assertProgress === 'function') {
                window.MVC.Hook.Hero.assertProgress(torrent.infoHash);
            }

            // 1. Capture raw binary .torrent file buffer generated by WebTorrent
            const torrentBuffer = torrent.torrentFile; // Uint8Array
            const torrentByteArray = Array.from(torrentBuffer);

            // 2. Construct Universal Ramosa Protocol Payload Structure with torrentBuffer on Sphere.Doc
            const defaultSource = RayPayLoad?.Sphere?.source || {
                uuid: `src_${torrent.infoHash.substring(0, 8)}`,
                name: torrent.name || "Archival Document",
                genus: "Document",
                date: new Date().toISOString().split('T')[0],
                cover: "https://via.placeholder.com/222x300?text=Torrent"
            };

            const defaultEdition = RayPayLoad?.Sphere?.edition || {
                uuid: `ed_${Math.random().toString(36).substring(2, 9)}`,
                title: torrent.name || "Archival Edition",
                date: new Date().toISOString().split('T')[0],
                created_at: Date.now(),
                webSeed: seedOptions.urlList[0] || ""
            };

            const rayPayload = RayPayLoad || {
                rayVersion: "1.0",
                categoryType: "TYPE_1_MODERN_SCAN",
                Sphere: {
                    source: defaultSource,
                    edition: defaultEdition,
                    Doc: [{
                        format: "PDF",
                        size: torrent.length || fileOrSource.size || 0,
                        snatches: 1,
                        RAy: torrent.infoHash,
                        infoHash: torrent.infoHash,
                        webseeds: seedOptions.urlList,
                        torrentBuffer: torrentByteArray
                    }]
                }
            };

            // Ensure Sphere.Doc has the binary buffer and metadata correctly populated
            if (rayPayload.Sphere) {
                const docObj = {
                    format: "PDF",
                    size: torrent.length || fileOrSource.size || 0,
                    snatches: 1,
                    RAy: torrent.infoHash,
                    infoHash: torrent.infoHash,
                    webseeds: seedOptions.urlList,
                    torrentBuffer: torrentByteArray
                };

                if (!rayPayload.Sphere.Doc) {
                    rayPayload.Sphere.Doc = [docObj];
                } else if (Array.isArray(rayPayload.Sphere.Doc)) {
                    rayPayload.Sphere.Doc.forEach(d => {
                        d.RAy = d.RAy || torrent.infoHash;
                        d.infoHash = d.infoHash || torrent.infoHash;
                        d.torrentBuffer = d.torrentBuffer || torrentByteArray;
                    });
                    if (rayPayload.Sphere.Doc.length === 0) {
                        rayPayload.Sphere.Doc.push(docObj);
                    }
                } else {
                    rayPayload.Sphere.Doc.RAy = rayPayload.Sphere.Doc.RAy || torrent.infoHash;
                    rayPayload.Sphere.Doc.infoHash = rayPayload.Sphere.Doc.infoHash || torrent.infoHash;
                    rayPayload.Sphere.Doc.torrentBuffer = rayPayload.Sphere.Doc.torrentBuffer || torrentByteArray;
                }
            }

            // 3. Commit into IndexedDB via Base.Ramosa.put() without clobbering Doc
            const ramosaBase = window.MVC?.Base?.Ramosa;
            if (ramosaBase && typeof ramosaBase.put === 'function') {
                await ramosaBase.put(torrent.infoHash, rayPayload);
                console.info(`[RAMOSA BASE] Successfully anchored seeded torrent record & binary buffer into IndexedDB: ${torrent.infoHash}`);
                
                if (window.MVC?.Control?.Table && typeof window.MVC.Control.Table.unfold === 'function') {
                    window.MVC.Control.Table.unfold("table");
                }
            } else {
                console.warn("[RAMOSA BASE] MVC.Base.Ramosa.put not found during seeding.");
            }

            // 4. Trigger download of the .torrent file to browser
            const torrentBlob = new Blob([torrentBuffer], { type: 'application/x-bittorrent' });
            const blobUrl = URL.createObjectURL(torrentBlob);
            const fileName = `${torrent.name || 'archive'}.torrent`;

            const downloadLink = document.createElement('a');
            downloadLink.style.display = 'none';
            downloadLink.href = blobUrl;
            downloadLink.download = fileName;
            
            document.body.appendChild(downloadLink);
            downloadLink.click();
            
            setTimeout(() => {
                document.body.removeChild(downloadLink);
                window.URL.revokeObjectURL(blobUrl);
            }, 1000);

            torrent.RAy = torrent.infoHash;
            if (typeof cb === 'function') cb(torrent);
        });
    },

    propagate: function(info) {
        try {
            console.info("[MVC.Control.webtorrent] propagate() invoked with torrent info:", info);
            
            if (!info) {
                console.warn("[MVC.Control.webtorrent] propagate() aborted: info object is null or empty.");
                return;
            }

            const client = window.client || window.webtorrentClient;
            if (!client) {
                console.error("[MVC.Control.webtorrent] WebTorrent client (window.client) not found during propagate()");
                return;
            }

            let infoHash = info.infoHash || info.RAy || info.index;
            let torrentSource = null;
            let webseeds = [];

            const extractDoc = (doc) => {
                if (!doc) return;
                if (doc.RAy || doc.infoHash) infoHash = infoHash || doc.RAy || doc.infoHash;
                if (Array.isArray(doc.webseeds)) webseeds.push(...doc.webseeds);
                if (doc.webseed) webseeds.push(doc.webseed);
                
                if (doc.torrentBuffer) {
                    console.info("[MVC.Control.webtorrent] Successfully resolved stored binary .torrent buffer from IndexedDB!");
                    torrentSource = new Uint8Array(doc.torrentBuffer);
                }
            };

            // Inspect Sphere.Doc
            if (info.Sphere) {
                if (Array.isArray(info.Sphere.Doc)) {
                    info.Sphere.Doc.forEach(extractDoc);
                } else if (info.Sphere.Doc) {
                    extractDoc(info.Sphere.Doc);
                }
                if (info.Sphere.edition?.webSeed) {
                    webseeds.push(info.Sphere.edition.webSeed);
                }
            }

            // Inspect root-level Doc
            if (info.Doc) {
                if (Array.isArray(info.Doc)) {
                    info.Doc.forEach(extractDoc);
                } else {
                    extractDoc(info.Doc);
                }
            }

            // Fallback to Magnet URI if binary buffer is missing
            if (!torrentSource) {
                if (!infoHash) {
                    console.error("[MVC.Control.webtorrent] Could not resolve infoHash or torrentBuffer from record:", info);
                    return;
                }
                torrentSource = `magnet:?xt=urn:btih:${infoHash}`;
                console.info("[MVC.Control.webtorrent] Using Magnet URI fallback:", torrentSource);
            }

            if (info.webseeds && Array.isArray(info.webseeds)) {
                webseeds.push(...info.webseeds);
            }

            console.info("[MVC.Control.webtorrent] Resolved target infoHash:", infoHash);

            if (window.MVC?.Hook?.Hero && typeof window.MVC.Hook.Hero.assertProgress === 'function') {
                window.MVC.Hook.Hero.assertProgress(infoHash);
            }

            const downloadFile = (torrent) => {
                if (!torrent || !torrent.files || torrent.files.length === 0) {
                    console.warn("[MVC.Control.webtorrent] Torrent has no files available to download.");
                    return;
                }
                const file = torrent.files[0];
                if (!file) return;

                console.info("[MVC.Control.webtorrent] Fetching blob for file:", file.name);
                file.getBlob(function(err, blob) {
                    if (err) {
                        console.error("[MVC.Control.webtorrent] Error getting file blob:", err);
                        return;
                    }
                    const url = URL.createObjectURL(blob);
                    const a = document.createElement('a');
                    a.href = url;
                    a.download = file.name;
                    document.body.appendChild(a);
                    a.click();
                    window.URL.revokeObjectURL(url);
                    a.remove();
                    console.info("[MVC.Control.webtorrent] File successfully dispatched to browser downloads folder:", file.name);
                });
            };

            const onTorrentReady = (torrent) => {
                if (!torrent) return;

                if (typeof torrent.on === 'function') {
                    torrent.on("progress", () => {
                        if (window.MVC?.Hook?.Hero && typeof window.MVC.Hook.Hero.assertProgress === 'function') {
                            window.MVC.Hook.Hero.assertProgress(torrent.infoHash);
                        }
                    });
                }

                if (torrent.done || (torrent.files && torrent.files.length > 0 && torrent.progress === 1)) {
                    downloadFile(torrent);
                } else if (typeof torrent.on === 'function') {
                    torrent.on('done', () => {
                        downloadFile(torrent);
                    });
                } else {
                    const checkInterval = setInterval(() => {
                        if (torrent.done || (torrent.files && torrent.files.length > 0)) {
                            clearInterval(checkInterval);
                            downloadFile(torrent);
                        }
                    }, 1000);
                }
            };

            console.info("[MVC.Control.webtorrent] Adding torrent source directly with webseeds:", webseeds);

            const opts = {
                urlList: webseeds,
                dht: false,
                tracker: false,
                pex: true
            };

            client.add(torrentSource, opts, (torrent) => {
                if (!torrent) return;
                
                if (torrent.ready || (torrent.files && torrent.files.length > 0)) {
                    onTorrentReady(torrent);
                } else if (typeof torrent.on === 'function') {
                    torrent.on('ready', () => onTorrentReady(torrent));
                } else {
                    const poll = setInterval(() => {
                        if (torrent.files && torrent.files.length > 0) {
                            clearInterval(poll);
                            onTorrentReady(torrent);
                        }
                    }, 500);
                }
            });
        
        } catch (err) {
            console.error("[MVC.Control.webtorrent ERROR] Uncaught exception inside propagate():", err);
        }
    }
};

export default WebTorrentControl;